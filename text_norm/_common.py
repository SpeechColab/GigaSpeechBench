"""
通用副语言标签和填充词移除模块。

副语言通用标签（来自标注规范）：
  [breath]        呼吸
  [chocking]      哽咽
  [humph]         哼声
  [sigh]          叹气
  [laugh]         笑声
  [cough]         咳嗽
  [hissing]       嘶声
  [Throat clear]  清嗓子

填充词标注规范：
  #word  说话者犹豫/思考时使用的填充词，前面添加 # 号。
         例如：# 呃、# أأأ、# eh

其他常见标注：
  <unk>           未知片段
  (noise)         噪音
  (overlap)       重叠语音
  (~)             拖尾
  (sil)           静音
"""

import re

# ──────────────────────────────────────────────
# 1. 方括号标签  [breath], [laugh], ...
# ──────────────────────────────────────────────
_RE_SQUARE = re.compile(r"\[[^\]]*\]")

# ──────────────────────────────────────────────
# 2. 尖括号标签  <unk>, ...
# ──────────────────────────────────────────────
_RE_ANGLE = re.compile(r"<[^>]*>")

# ──────────────────────────────────────────────
# 3. 圆括号标签  (noise), (overlap), (~), ...
#    注意：只移除 "标签类" 短内容（≤30字符），
#    避免误删真正的括号注释文本
# ──────────────────────────────────────────────
_RE_PAREN = re.compile(r"\([^)]{0,30}\)")
_RE_PAREN_CN = re.compile(r"（[^）]{0,30}）")

# ──────────────────────────────────────────────
# 4. 花括号标签  {breath}, ...
# ──────────────────────────────────────────────
_RE_BRACE = re.compile(r"\{[^}]*\}")

# ──────────────────────────────────────────────
# 5. 填充词标记  # word
#    匹配 # 后跟可选空格再跟一个"词"（含尾随标点）
#    例如: "# أأأ"  "# eh,"  "# อ่า"
# ──────────────────────────────────────────────
_RE_FILLER = re.compile(r"#\s*\S+")

# ──────────────────────────────────────────────
# 6. 合并多余空白
# ──────────────────────────────────────────────
_RE_MULTI_SPACE = re.compile(r"\s+")


def remove_paralinguistic_tags(text: str) -> str:
    """
    移除所有副语言标签和填充词标注，返回清理后的文本。

    处理顺序：
      1. [...]  方括号标签
      2. <...>  尖括号标签
      3. (...)  圆括号标签（短内容）
      4. （...）全角圆括号标签（短内容）
      5. {...}  花括号标签
      6. # word 填充词
      7. 合并多余空格
    """
    text = _RE_SQUARE.sub("", text)
    text = _RE_ANGLE.sub("", text)
    text = _RE_PAREN.sub("", text)
    text = _RE_PAREN_CN.sub("", text)
    text = _RE_BRACE.sub("", text)
    text = _RE_FILLER.sub("", text)
    text = _RE_MULTI_SPACE.sub(" ", text).strip()
    return text
